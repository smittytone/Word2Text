// swift-tools-version: 5.10

import PackageDescription

/*
 This package definition was originally written to support CLI building of the word2text utility under Linux.
 This is because macOS users are expected to build using Xcode and the Xcode project files in this repository,
 and Linux users can't do this because (surprise, surprise) there's no Xcdoe for Linux.

 It has been updated to support the use of core files minus the host CLI code within third-party apps, currently
 macOS only. This is currently experimental.
 */

let package = Package(
    name: "word2text",
    platforms: [
        .macOS(.v12)
    ],
    products: [
        .library(name: "Word2text", targets: ["word2text-lib"]),
        .executable(name: "word2text", targets: ["word2text"])
    ],
    dependencies: [
        .package(url: "https://github.com/smittytone/clicore", from: "0.8.0"),
    ],
    targets: [
        .executableTarget(
            name: "word2text",
            dependencies: [
                .product(name: "Clicore", package: "clicore")
            ],
            path: "word2text",
            exclude: [
                // `Info.plist` is not a Swift source file, so its must be excluded
                // from macOS or Linux builds generated by calling the Swift compiler
                "Info.plist",
                "swift.plist",
                "logging_lib.swift",
                "lib/logging_lib.swift",
                "lib/psion_word.swift",
                "lib/entities.swift"
            ],
            linkerSettings: [
                // Embed `swift.plist` into the __TEXT,__info_plist Mach-O section so the binary
                // can be signed and notarized. `.unsafeFlags` is fine here because `dlist` is
                // a top-level executable, not a library dependency.
                // macOS only: Linux has no Mach-O format and no notarization requirement.
                .unsafeFlags(
                    ["-Xlinker", "-sectcreate",
                     "-Xlinker", "__TEXT",
                     "-Xlinker", "__info_plist",
                     "-Xlinker", "word2text/swift.plist"],
                    .when(platforms: [.macOS])
                )
            ]
        ),
        .target(
            name: "word2text-lib",
            path: "word2text/lib",
            sources: [
                // Just include the files needed for macOS lib usage
                "psion_word.swift",
                "entities.swift",
                "logging_lib.swift"
            ]
        )
    ]
)
